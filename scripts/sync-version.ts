import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { resolve } from 'node:path'
import semver from 'semver'

export const repoRoot = fileURLToPath(new URL('..', import.meta.url))

export function pythonVersion(version: string): string {
  if (!semver.valid(version)) throw new Error(`Invalid semantic version: ${version}`)
  // Keep Python package metadata valid PEP 440 while the application reports
  // the original SemVer string (for example 0.6.0-rc.1).
  const match = /^(\d+\.\d+\.\d+)(?:-(alpha|beta|rc)\.(\d+))?$/.exec(version)
  if (!match) throw new Error('Use a stable version or an alpha.N, beta.N, or rc.N prerelease.')
  const suffixes: Record<string, string> = { alpha: 'a', beta: 'b', rc: 'rc' }
  const suffix = suffixes[match[2]]
  return match[1] + (suffix ? `${suffix}${match[3]}` : '')
}

function replaceOne(source: string, pattern: RegExp, replacement: string, label: string): string {
  if ([...source.matchAll(pattern)].length !== 1) {
    throw new Error(`Expected exactly one ${label}`)
  }
  return source.replace(pattern, replacement)
}

interface PackageMetadata { version: string }
interface Lockfile extends PackageMetadata { packages: Record<string, PackageMetadata> }

export function syncVersion(
  root = repoRoot,
  { check = false, releaseTag }: { check?: boolean; releaseTag?: string } = {},
) {
  const read = (path: string) => readFileSync(resolve(root, path), 'utf8')
  const { version } = JSON.parse(read('package.json')) as PackageMetadata
  const python = pythonVersion(version)
  if (releaseTag && releaseTag !== `v${version}`) {
    throw new Error(`Release tag ${releaseTag} does not match version v${version}`)
  }
  const updates = new Map<string, string>()
  const updateJson = <T>(path: string, transform: (document: T) => void) => {
    const source = read(path)
    const document = JSON.parse(source) as T
    transform(document)
    const output = JSON.stringify(document, null, 2) + '\n'
    updates.set(path, source.includes('\r\n') ? output.replaceAll('\n', '\r\n') : output)
  }

  updateJson<Lockfile>('package-lock.json', (document) => {
    document.version = version
    document.packages[''].version = version
  })
  updateJson<PackageMetadata>('frontend/package.json', (document) => { document.version = version })
  updateJson<Lockfile>('frontend/package-lock.json', (document) => {
    document.version = version
    document.packages[''].version = version
  })
  updates.set('backend/pyproject.toml', replaceOne(
    read('backend/pyproject.toml'), /^version = "[^"]+"/gm,
    `version = "${python}"`, 'backend project version',
  ))
  const versionPath = 'backend/app/core/version.py'
  const versionNewline = read(versionPath).includes('\r\n') ? '\r\n' : '\n'
  updates.set(versionPath, [
    '"""Generated by npm run version:sync; edit the root package.json instead."""',
    '',
    `APP_VERSION: str = ${JSON.stringify(version)}`,
    '',
  ].join(versionNewline))

  const gradlePath = 'frontend/android/app/build.gradle'
  const gradle = read(gradlePath)
  const previousVersion = /^\s*versionName "([^"]+)"/m.exec(gradle)?.[1]
  const codeMatch = /^(\s*versionCode )(\d+)/m.exec(gradle)
  if (!previousVersion || !codeMatch) throw new Error('Android version metadata is missing')
  const code = Number(codeMatch[2]) + (previousVersion === version ? 0 : 1)
  if (!Number.isSafeInteger(code) || code < 1 || code > 2100000000) {
    throw new Error('Android versionCode must be between 1 and 2100000000')
  }
  updates.set(gradlePath, replaceOne(
    replaceOne(gradle, /^(\s*versionName )"[^"]+"/gm, `$1"${version}"`, 'Android versionName'),
    /^(\s*versionCode )\d+/gm, `$1${code}`, 'Android versionCode',
  ))

  // Validate every input before writing anything, so a malformed file cannot
  // leave just part of the repository updated.
  const changed = [...updates].filter(([path, content]) => read(path) !== content)
  if (check) {
    const schemaVersion = JSON.parse(read('frontend/src/api/openapi.json')).info.version
    const stale = changed.map(([path]) => path)
    if (schemaVersion !== version) stale.push('frontend/src/api/openapi.json (run npm --prefix frontend run api:generate)')
    if (stale.length) throw new Error(`Version ${version} is out of sync:\n${stale.join('\n')}`)
  } else {
    for (const [path, content] of changed) writeFileSync(resolve(root, path), content)
  }
  return { version, changed: changed.map(([path]) => path) }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const args = process.argv.slice(2)
    if (args.some((arg) => arg !== '--check')) throw new Error('Usage: node scripts/sync-version.ts [--check]')
    const result = syncVersion(repoRoot, { check: args.includes('--check'), releaseTag: process.env.RELEASE_TAG })
    console.log(`OpenVoyage ${result.version}: ${args.includes('--check') ? 'versions match' : `synchronized ${result.changed.length} files`}`)
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error))
    process.exitCode = 1
  }
}
